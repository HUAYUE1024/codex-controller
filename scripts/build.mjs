import {readFile, writeFile, rename, rm} from 'node:fs/promises';
import {spawnSync} from 'node:child_process';
import path from 'node:path';
import {fileURLToPath} from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const sources = ['src/voice-input.js', 'src/local-recognition.js', 'src/activity-view.js', 'src/gamepad-controls.js', 'src/controller-pilot.js', 'src/app.js'];
const contents = await Promise.all(sources.map(file => readFile(path.join(root, file), 'utf8')));
const bundle = '// Generated by npm run build. Edit src/, not this bundle.\n' +
  contents.map((content, i) => `\n/* ${sources[i]} */\n${content.trim()}\n`).join('\n');
const output = path.join(root, 'public/app.js');
const temporary = path.join(root, `public/.app-build-${process.pid}.js`);
try {
  await writeFile(temporary, bundle, 'utf8');
  const check = spawnSync(process.execPath, ['--check', temporary], {encoding: 'utf8', windowsHide: true});
  if (check.status !== 0) throw new Error(check.stderr || check.error?.message || 'Bundle syntax check failed');
  const worklet=await readFile(path.join(root,'src/voice-worklet.js'),'utf8');
  const workletCheck=spawnSync(process.execPath,['--check','--input-type=commonjs'],{input:worklet,encoding:'utf8',windowsHide:true});
  if(workletCheck.status!==0)throw new Error(workletCheck.stderr||'Audio worklet syntax check failed');
  await writeFile(path.join(root,'public/voice-worklet.js'),worklet,'utf8');
  await rename(temporary, output);
  console.log(`BUILD: ${sources.length} source files -> public/app.js (${Buffer.byteLength(bundle)} bytes)`);
} finally {
  await rm(temporary, {force: true});
}
